package cmd

import (
	"strings"
	"testing"

	"github.com/spf13/cobra"
	"github.com/stretchr/testify/require"
)

// Văn bản trợ giúp người dùng đọc phải gọi sản phẩm là agent-cli, không phải
// tên upstream (module, crush.json, biến CRUSH_* giữ nguyên, nhưng chúng không
// xuất hiện trong phần mô tả của các lệnh này).
func TestHelpTextNamesAgentCLI(t *testing.T) {
	// Không t.Parallel(): cobra gộp cờ persistent của cha vào Flags() khi một test khác
	// thực thi lệnh, và đọc FlagSet lúc đang bị ghi là data race.
	for _, c := range []*cobra.Command{dirsCmd, logsCmd, loginCmd, logoutCmd, schemaCmd, statsCmd} {
		// LocalFlags: chỉ cờ khai riêng cho lệnh này, không lẫn cờ kế thừa từ lệnh gốc
		// (giá trị mặc định của --host có chữ crush trong đường dẫn socket).
		text := strings.Join([]string{c.Short, c.Long, c.Example, c.LocalFlags().FlagUsages()}, "\n")
		require.NotContains(t, strings.ToLower(text), "crush", "help of `%s` mentions the upstream name", c.Name())
	}

	// Mô tả dài của các lệnh này nêu tên sản phẩm bằng đúng chữ agent-cli.
	require.Contains(t, dirsCmd.Long, "Show where agent-cli stores")
	require.Contains(t, logsCmd.Long, "logs generated by agent-cli")
	require.Contains(t, loginCmd.Long, "Login agent-cli to")
	require.Contains(t, logoutCmd.Long, "Logout agent-cli from")
	require.Contains(t, schemaCmd.Long, "agent-cli configuration file")
	require.Contains(t, statsCmd.Flags().Lookup("crawl-dir").Usage, "agent-cli projects")
}
