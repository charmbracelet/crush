const defaultTailLines = 1000

var logsCmd = &cobra.Command{
	Use:   "logs",
	Short: "View crush logs",
	Long:  `View the logs generated by Crush. This command allows you to see the log output for debugging and monitoring.`,
	RunE: func(cmd *cobra.Command, args []string) error {
		cwd, err := cmd.Flags().GetString("cwd")
		if err != nil {
			return fmt.Errorf("failed to get current working directory: %v", err)
		}

		dataDir, err := cmd.Flags().GetString("data-dir")
		if err != nil {
			return fmt.Errorf("failed to get data directory: %v", err)
		}

		follow, err := cmd.Flags().GetBool("follow")
		if err != nil {
			return fmt.Errorf("failed to get follow flag: %v", err)
		}

		tailLines, err := cmd.Flags().GetInt("tail")
		if err != nil {
			return fmt.Errorf("failed to get tail flag: %v", err)
		}

		log.SetLevel(log.DebugLevel)
		log.SetOutput(os.Stdout)
		if !term.IsTerminal(os.Stdout.Fd()) {
			log.SetColorProfile(colorprofile.NoTTY)
		}

		cfg, err := config.Load(cmd.Context(), cwd, dataDir, false)
		if err != nil {
			return fmt.Errorf("failed to load configuration: %v", err)
		}
		logsFiles := []string{filepath.Join(cfg.Config().Options.DataDirectory, "logs", "crush.log")}
		if useClientServer() {
			// The agent runs in the server, which keeps its own log, and
			// clients log their startup next to it.
			hostURL, err := server.ParseHostURL(clientHost)
			if err != nil {
				return fmt.Errorf("invalid host URL: %v", err)
			}
			logsFiles = append(logsFiles, clientLogFile(hostURL), serverLogFile(hostURL))
		}
		logsFiles = slices.DeleteFunc(logsFiles, func(logsFile string) bool {
			_, err := os.Stat(logsFile)
			return os.IsNotExist(err)
		})
		if len(logsFiles) == 0 {
			log.Warn("Looks like you are not in a crush project. No logs found.")
			return nil
		}

		if follow {
			return followLogs(cmd.Context(), logsFiles, tailLines)
		}

		return showLogs(logsFiles, tailLines)
	},
}

func init() {
	logsCmd.Flags().BoolP("follow", "f", false, "Follow log output")
	logsCmd.Flags().IntP("tail", "t", defaultTailLines, "Show only the last N lines default: 1000 for performance")
}

func followLogs(ctx context.Context, logsFiles []string, tailLines int) error {
	lines, err := lastLogLines(logsFiles, tailLines)
	if err != nil {
		return err
	}

	for _, line := range lines {
		printLogLine(line)
	}

	if len(lines) == tailLines {
		fmt.Fprintf(os.Stderr, "\nShowing last %d lines. Full logs available at: %s\n", tailLines, strings.Join(logsFiles, ", "))
		fmt.Fprintf(os.Stderr, "Following new log entries...\n\n")
	}

	newLines := make(chan string)
	for _, logsFile := range logsFiles {
		t, err := tail.TailFile(logsFile, tail.Config{
			Follow:   true,
			ReOpen:   true,
			Logger:   tail.DiscardingLogger,
			Location: &tail.SeekInfo{Offset: 0, Whence: io.SeekEnd},
		})
		if err != nil {
			return fmt.Errorf("failed to tail log file: %v", err)
		}
		defer t.Stop()
		go func() {
			for line := range t.Lines {
				if line.Err != nil {
					continue
				}
				select {
				case newLines <- line.Text:
				case <-ctx.Done():
					return
				}
			}
		}()
	}

	for {
		select {
		case line := <-newLines:
			printLogLine(line)
		case <-ctx.Done():
			return nil
		}
	}
}

func showLogs(logsFiles []string, tailLines int) error {
	lines, err := lastLogLines(logsFiles, tailLines)
	if err != nil {
		return err
	}

	for _, line := range lines {
		printLogLine(line)
	}

	if len(lines) == tailLines {
		fmt.Fprintf(os.Stderr, "\nShowing last %d lines. Full logs available at: %s\n", tailLines, strings.Join(logsFiles, ", "))
	}

	return nil
}

// lastLogLines returns the last tailLines lines of logsFiles. Lines of
// several files are interleaved in the order they were logged.
func lastLogLines(logsFiles []string, tailLines int) ([]string, error) {
	var lines []string
	for _, logsFile := range logsFiles {
		t, err := tail.TailFile(logsFile, tail.Config{
			Follow:      false,
			ReOpen:      false,
			Logger:      tail.DiscardingLogger,
			MaxLineSize: 0,
		})
		if err != nil {
			return nil, fmt.Errorf("failed to tail log file: %v", err)
		}

		var fileLines []string
		for line := range t.Lines {
			if line.Err != nil {
				continue
			}
			fileLines = append(fileLines, line.Text)
			if len(fileLines) > tailLines {
				fileLines = fileLines[len(fileLines)-tailLines:]
			}
		}
		t.Stop()
		lines = append(lines, fileLines...)
	}
	if len(logsFiles) < 2 {
		return lines, nil
	}

	type timedLine struct {
		time time.Time
		text string
	}
	timed := make([]timedLine, len(lines))
	for i, text := range lines {
		var entry struct {
			Time time.Time `json:"time"`
		}
		_ = json.Unmarshal([]byte(text), &entry)
		timed[i] = timedLine{time: entry.Time, text: text}
	}
	slices.SortStableFunc(timed, func(a, b timedLine) int {
		return a.time.Compare(b.time)
	})
	lines = lines[:0]
	for _, line := range timed[max(len(timed)-tailLines, 0):] {
		lines = append(lines, line.text)
	}
	return lines, nil
}

func printLogLine(lineText string) {
	var data map[string]any
	if err := json.Unmarshal([]byte(lineText), &data); err != nil {
		return
	}
	msg := data["msg"]
	level := data["level"]
	var otherData []any
	var keys []string
	for k := range data {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	for _, k := range keys {
		switch k {
		case "msg", "level", "time":
			continue
		case "source":
			source, ok := data[k].(map[string]any)
			if !ok {
				continue
			}
			sourceFile := fmt.Sprintf("%s:%d", source["file"], int(source["line"].(float64)))
			otherData = append(otherData, "source", sourceFile)

		default:
			otherData = append(otherData, k, data[k])
		}
	}
	log.SetTimeFunction(func(_ time.Time) time.Time {
		// parse the timestamp from the log line if available
		t, err := time.Parse(time.RFC3339, data["time"].(string))
		if err != nil {
			return time.Now() // fallback to current time if parsing fails
		}
		return t
	})
	switch level {
	case "INFO":
		log.Info(msg, otherData...)
	case "DEBUG":
		log.Debug(msg, otherData...)
	case "ERROR":
		log.Error(msg, otherData...)
	case "WARN":
		log.Warn(msg, otherData...)
	default:
		log.Info(msg, otherData...)
	}
}
